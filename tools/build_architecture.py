"""Build the data product catalog and domain map from architecture/data-products.yaml.

  python3 tools/build_architecture.py            # validate, write catalog + domain map
  python3 tools/build_architecture.py --render   # also render every diagrams/*.mmd to .svg and .png
  python3 tools/build_architecture.py --check    # validate and fail if generated files are stale (CI)

Rendering uses Mermaid CLI: `mmdc` on PATH, $MMDC, or `npx -y @mermaid-js/mermaid-cli`.
"""
import argparse, hashlib, json, os, pathlib, re, shutil, subprocess, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
ARCH = ROOT / "architecture"
DIAG = ARCH / "diagrams"
MANIFEST = DIAG / "rendered.json"  # source hash of each diagram at its last render
SPEC = yaml.safe_load((ARCH / "data-products.yaml").read_text())
QUESTIONS = yaml.safe_load((ROOT / "questionnaire/questions.yaml").read_text())
QIDS = {f"{d['code']}-{i:02d}" for d in QUESTIONS["domains"] for i, _ in enumerate(d["questions"], 1)}
GUIDES = {p.name.split("-")[0]: p for p in (ROOT / "labs/guides").glob("*/*.md") if p.name != "README.md"}
TYPES = ["source-aligned", "aggregate", "consumer-aligned", "feature-set", "vector-index", "model", "ai-app"]
SHAPE = {  # Mermaid node shape per product type
    "source-aligned": ("[", "]"), "aggregate": ("[", "]"), "consumer-aligned": ("[", "]"),
    "feature-set": ("[[", "]]"), "vector-index": ("[(", ")]"), "model": ("{{", "}}"), "ai-app": ("([", "])"),
}
STYLE = {
    "source-aligned": "fill:#e8f1fb,stroke:#0672cb", "aggregate": "fill:#d4e6f7,stroke:#0672cb",
    "consumer-aligned": "fill:#b9d6f2,stroke:#0672cb", "feature-set": "fill:#fff4d6,stroke:#b07d00",
    "vector-index": "fill:#e6f4ea,stroke:#2e7d32", "model": "fill:#fde7e9,stroke:#c62828",
    "ai-app": "fill:#f1e6fa,stroke:#6a1b9a",
}


def validate():
    errors = []
    domains = {d["id"] for d in SPEC["domains"]}
    sources = {s["id"] for s in SPEC["sources"]}
    consumers = {c["id"] for c in SPEC["consumers"]}
    products = {p["id"] for p in SPEC["products"]}
    conv = SPEC["conventions"]
    for p in SPEC["products"]:
        pid = p["id"]
        need = ["domain", "type", "description", "classification", "engine", "serve", "inputs", "freshness", "quality",
                "consumers", "labs", "questions"]
        errors += [f"{pid}: missing {k}" for k in need if k not in p]
        if pid.split(".")[0] != p.get("domain") or p.get("domain") not in domains:
            errors.append(f"{pid}: id must start with its domain, and the domain must exist")
        if p.get("type") not in TYPES:
            errors.append(f"{pid}: type {p.get('type')} not in {TYPES}")
        if p.get("classification") not in conv["classification"]:
            errors.append(f"{pid}: classification {p.get('classification')} not in {conv['classification']}")
        if p.get("type") in TYPES[:4] and p.get("layer") not in conv["layers"]:
            errors.append(f"{pid}: table products need a layer from {conv['layers']}")
        errors += [f"{pid}: unknown input {i}" for i in p.get("inputs", []) if i not in products | sources]
        errors += [f"{pid}: input {i} is itself" for i in p.get("inputs", []) if i == pid]
        errors += [f"{pid}: unknown consumer {c}" for c in p.get("consumers", []) if c not in consumers]
        errors += [f"{pid}: unknown question {q}" for q in p.get("questions", []) if q not in QIDS]
        errors += [f"{pid}: no guide for lab {l}" for l in p.get("labs", []) if l not in GUIDES]
    if len(products) != len(SPEC["products"]):
        errors.append("duplicate product id")
    used = {i for p in SPEC["products"] for i in p["inputs"]} | {c for p in SPEC["products"] for c in p["consumers"]}
    errors += [f"{x}: declared but never used" for x in sorted((sources | consumers) - used)]
    return errors


def address(p, env="prod"):
    d, name = p["domain"], p["id"].split(".", 1)[1]
    if p["type"] in TYPES[:4]:
        return f"`iceberg.{env}_{d}_{p['layer']}.{name}`"
    if p["type"] == "vector-index":
        return f"index `{env}-{d}-{name.replace('_', '-')}`"
    if p["type"] == "model":
        return f"model `{p['id']}@champion`"
    return p["serve"]


def node(x):
    return re.sub(r"\W", "_", x)


def domain_map():
    out = ["%% Generated by tools/build_architecture.py from architecture/data-products.yaml - do not edit.",
           "flowchart LR"]
    out.append('  subgraph SRC["Operational sources"]')
    out += [f'    {node(s["id"])}["{s["name"]}"]' for s in SPEC["sources"]]
    out.append("  end")
    for d in SPEC["domains"]:
        out.append(f'  subgraph D_{d["id"]}["{d["name"]} domain<br/>owner: {d["owner"]}"]')
        for p in (p for p in SPEC["products"] if p["domain"] == d["id"]):
            o, c = SHAPE[p["type"]]
            out.append(f'    {node(p["id"])}{o}"{p["id"]}<br/><i>{p["type"]} - {p["classification"]}</i>"{c}')
        out.append("  end")
    out.append('  subgraph CON["Consumers"]')
    out += [f'    {node(c["id"])}["{c["name"]}"]' for c in SPEC["consumers"]]
    out.append("  end")
    for p in SPEC["products"]:
        out += [f"  {node(i)} --> {node(p['id'])}" for i in p["inputs"]]
    for p in SPEC["products"]:
        out += [f"  {node(p['id'])} --> {node(c)}" for c in p["consumers"]]
    for t, s in STYLE.items():
        out.append(f"  classDef {node(t)} {s}")
        ids = [node(p["id"]) for p in SPEC["products"] if p["type"] == t]
        if ids:
            out.append(f"  class {','.join(ids)} {node(t)}")
    out.append("  classDef ext fill:#f5f5f5,stroke:#7a7a7a")
    out.append("  class " + ",".join(node(x["id"]) for x in SPEC["sources"] + SPEC["consumers"]) + " ext")
    return "\n".join(out) + "\n"


def catalog():
    by_id = {p["id"]: p for p in SPEC["products"]}
    names = {x["id"]: x["name"] for x in SPEC["sources"] + SPEC["consumers"]}
    downstream = {p["id"]: [q["id"] for q in SPEC["products"] if p["id"] in q["inputs"]] for p in SPEC["products"]}
    lab = lambda l: f"[{l}](../{GUIDES[l].relative_to(ROOT).as_posix()})"
    ref = lambda x: f"`{x}`" if x in by_id else names[x]
    L = ["# Sample data product catalog", "",
         "Generated by [`tools/build_architecture.py`](../tools/build_architecture.py) from "
         "[`data-products.yaml`](data-products.yaml). Edit the YAML, not this file.", "",
         f"{len(SPEC['domains'])} domains, {len(SPEC['products'])} data products. Addresses are shown for `prod`; "
         "`dev` and `qa` use the same names with their own prefix (see [conventions](README.md#naming-conventions)).",
         "", "| Domain | Owner | Steward | Team | Products |", "|---|---|---|---|---|"]
    for d in SPEC["domains"]:
        n = sum(p["domain"] == d["id"] for p in SPEC["products"])
        L.append(f"| [{d['name']}](#{d['id']}) | {d['owner']} | {d['steward']} | `{d['team']}` | {n} |")
    for d in SPEC["domains"]:
        L += ["", f'<a id="{d["id"]}"></a>', f"## {d['name']} (`{d['id']}`)", "", d["description"], ""]
        for p in (p for p in SPEC["products"] if p["domain"] == d["id"]):
            used_by = [ref(x) for x in downstream[p["id"]] + p["consumers"]] or ["-"]
            L += [f"### `{p['id']}`", "", p["description"], "",
                  "| Contract | Value |", "|---|---|",
                  f"| Type | {p['type']} |",
                  f"| Classification | {p['classification']} |",
                  f"| Address (prod) | {address(p)} |",
                  f"| Built by | {p['engine']} |",
                  f"| Served by | {p['serve']} |",
                  f"| Inputs | {', '.join(ref(i) for i in p['inputs'])} |",
                  f"| Used by | {', '.join(used_by)} |",
                  f"| Freshness SLO | {p['freshness']} |",
                  f"| Quality gate | {'; '.join(p['quality'])} |",
                  f"| Labs | {', '.join(lab(l) for l in p['labs'])} |",
                  f"| Questionnaire | {', '.join(f'`{q}`' for q in p['questions'])} |", ""]
    return "\n".join(L).rstrip() + "\n"


def mmdc():
    if os.environ.get("MMDC"):
        return [os.environ["MMDC"]]
    if shutil.which("mmdc"):
        return ["mmdc"]
    if shutil.which("npx"):
        return ["npx", "-y", "@mermaid-js/mermaid-cli"]
    sys.exit("Mermaid CLI not found: npm i -g @mermaid-js/mermaid-cli, or set MMDC")


def source_hash(src):
    return hashlib.sha256(src.read_bytes() + (DIAG / "mermaid.config.json").read_bytes()).hexdigest()[:16]


def render():
    cfg = DIAG / "mermaid.config.json"
    done = {}
    for src in sorted(DIAG.glob("*.mmd")):
        for ext, extra in (("svg", []), ("png", ["-s", "2"])):
            out = src.with_suffix(f".{ext}")
            subprocess.run(mmdc() + ["-q", "-i", str(src), "-o", str(out), "-c", str(cfg), "-b", "white"] + extra,
                           check=True)
            print(f"rendered {out.relative_to(ROOT)}")
        done[src.name] = source_hash(src)
    MANIFEST.write_text(json.dumps(done, indent=2) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    errors = validate()
    if errors:
        sys.exit("\n".join(errors))
    files = {DIAG / "02-domain-product-map.mmd": domain_map(), ARCH / "data-product-catalog.md": catalog()}
    if args.check:
        stale = [str(f.relative_to(ROOT)) for f, text in files.items() if not f.exists() or f.read_text() != text]
        rendered = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
        stale += [str(s.relative_to(ROOT)) + " changed since its .svg/.png were rendered" for s in sorted(DIAG.glob("*.mmd"))
                  if rendered.get(s.name) != source_hash(s)
                  or not (s.with_suffix(".svg").exists() and s.with_suffix(".png").exists())]
        if stale:
            sys.exit("stale (run with --render): " + ", ".join(stale))
        print("architecture OK")
        return
    for f, text in files.items():
        f.write_text(text)
        print(f"wrote {f.relative_to(ROOT)}")
    if args.render:
        render()


if __name__ == "__main__":
    main()
